"""Newsdesk world map outlines.

Downloads Natural Earth's 1:110m country outlines at a fixed commit, checks
the file against a known SHA-256, and rasterises it into worldmap.js: a
0.5° grid of country indices, run-length encoded per row. The page samples
that grid to draw the Map tab in Braille characters.

The result is committed. Neither the Pi nor the phone ever downloads map
shapes; run this again only to change the source or the grid.

Run with:  uv run build_map.py
"""

import hashlib
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "worldmap.js")

# Pinned: a commit, never a branch, and the hash of the file at that commit.
COMMIT = "ca96624a56bd078437bca8184e78163e5039ad19"
URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
       f"{COMMIT}/geojson/ne_110m_admin_0_countries.geojson")
SHA256 = "6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f"
MAX_BYTES = 5_000_000

STEP = 0.5            # degrees per grid cell
NORTH, SOUTH = 84, -56  # Antarctica left out: no news, and half the height
COLS = int(360 / STEP)
ROWS = int((NORTH - SOUTH) / STEP)

# Too small for the 1:110m outlines; drawn as a single dot at this point.
EXTRA = {"MT": ("Malta", 14.44, 35.90), "SG": ("Singapore", 103.82, 1.35)}
NAMES = {"US": "United States"}


def download():
    with urllib.request.urlopen(URL, timeout=60) as r:
        body = r.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        sys.exit("map source is larger than expected; refusing it")
    got = hashlib.sha256(body).hexdigest()
    if got != SHA256:
        sys.exit(f"map source checksum mismatch:\n  expected {SHA256}\n  got      {got}")
    return json.loads(body)


def rings(geometry):
    if geometry["type"] == "Polygon":
        yield from geometry["coordinates"]
    elif geometry["type"] == "MultiPolygon":
        for polygon in geometry["coordinates"]:
            yield from polygon


def rasterise(features):
    """Scanline fill, even-odd rule, sampled at each cell's centre."""
    grid = [[0] * COLS for _ in range(ROWS)]
    for index, feature in features:
        edges = []
        for ring in rings(feature["geometry"]):
            edges += zip(ring, ring[1:] + ring[:1])
        for row in range(ROWS):
            lat = NORTH - (row + 0.5) * STEP
            xs = sorted(x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
                        for (x1, y1), (x2, y2) in edges
                        if (y1 > lat) != (y2 > lat))
            for x0, x1 in zip(xs[::2], xs[1::2]):
                first = max(0, round((x0 + 180) / STEP - 0.5))
                last = min(COLS - 1, round((x1 + 180) / STEP - 0.5) - 1)
                for col in range(first, last + 1):
                    grid[row][col] = index
    return grid


def encode(row):
    """[value, run, value, run, ...] — most rows are a few dozen runs."""
    out, prev, run = [], row[0], 0
    for v in row:
        if v == prev:
            run += 1
        else:
            out += [prev, run]
            prev, run = v, 1
    return out + [prev, run]


def main():
    source = download()
    codes, names, labels, features = [None], [None], [None], []
    for feature in source["features"]:
        p = feature["properties"]
        code = p["ISO_A2_EH"] if p["ISO_A2_EH"] != "-99" else None
        codes.append(code)   # None: land with no ISO code (N. Cyprus, Somaliland)
        names.append(NAMES.get(code, p["NAME"]))
        labels.append([round(p["LABEL_X"], 2), round(p["LABEL_Y"], 2)])
        features.append((len(codes) - 1, feature))
    for code, (name, lon, lat) in EXTRA.items():
        codes.append(code); names.append(name); labels.append([lon, lat])

    grid = rasterise(features)
    data = {
        "source": f"Natural Earth 1:110m admin-0 countries @ {COMMIT[:12]}",
        "sha256": SHA256,
        "step": STEP, "north": NORTH, "west": -180, "cols": COLS, "rows": ROWS,
        "codes": codes, "names": names, "labels": labels,
        "grid": [encode(r) for r in grid],
    }
    with open(OUT, "w") as f:
        f.write("// Generated by build_map.py from Natural Earth (public domain). Do not edit.\n")
        f.write("window.WORLDMAP = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {OUT}: {len(codes) - 1} countries, {COLS}x{ROWS} grid, "
          f"{os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
